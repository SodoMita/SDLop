/*
  SDLop -- SDL_keyboard.h: keyboard state, key names and text input.

  Sources of key events (all of them end up in SDLOP_SendKeyEvent):
    * the async evdev worker (src/input/SDL_evdev.c) - primary source;
    * the X11 backend when evdev is unavailable (XWayland, sandboxes);
    * SDL_PushEvent() from an application (SDL_EVENT_KEY_DOWN/KEY_UP).

  Key *names* come from tables generated by tools/gen_keynames.py, so
  SDL_GetScancodeFromName("Left Shift") and friends behave exactly like SDL3.
*/

#include "../sdlop_internal.h"
#include "sdlop_keynames.h"

#include <string.h>

static bool sdlop_keystate[SDL_SCANCODE_COUNT];
static SDL_Keymod sdlop_modstate;

/* The platform key layout (the Wayland compositor's keymap), or NULL when the
   built-in tables are all we have. */
static const SDLOP_KeyLayout *sdlop_key_layout;

void SDLOP_SetKeyLayout(const SDLOP_KeyLayout *layout)
{
    sdlop_key_layout = layout;
}

const SDLOP_KeyLayout *SDLOP_GetKeyLayout(void)
{
    return sdlop_key_layout;
}

/* text input state */
static bool sdlop_text_input_enabled;
static SDL_Window *sdlop_text_input_window;
static SDL_PropertiesID sdlop_text_input_props;
static SDL_Rect sdlop_text_input_rect;
static int sdlop_text_input_cursor = -1;

