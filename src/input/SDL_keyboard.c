/* Names                                                                     */
/* ------------------------------------------------------------------------- */

static const SDLOP_KeyName *sdlop_find_name(const SDLOP_KeyName *table, int count, const char *name)
{
    int lo = 0, hi = count - 1;
    while (lo <= hi) {
        int mid = (lo + hi) / 2;
        int cmp = SDL_strcasecmp(table[mid].name, name);
        if (cmp == 0) {
            return &table[mid];
        }
        if (cmp < 0) {
            lo = mid + 1;
        } else {
            hi = mid - 1;
        }
    }
    return NULL;
}

const char *SDL_GetScancodeName(SDL_Scancode scancode)
{
    if (scancode < 0 || scancode >= SDLOP_NUM_SCANCODES || !sdlop_scancode_names[scancode]) {
        SDL_InvalidParamError("scancode");
        return NULL;
    }
    return sdlop_scancode_names[scancode];
}

SDL_Scancode SDL_GetScancodeFromName(const char *name)
{
    const SDLOP_KeyName *found;
    int count = (int)(sizeof(sdlop_scancode_names_by_name) / sizeof(sdlop_scancode_names_by_name[0]));

    if (!name || !name[0]) {
        SDL_InvalidParamError("name");
        return SDL_SCANCODE_UNKNOWN;
    }
    found = sdlop_find_name(sdlop_scancode_names_by_name, count, name);
    return found ? (SDL_Scancode)found->code : SDL_SCANCODE_UNKNOWN;
}

const char *SDL_GetKeyName(SDL_Keycode key)
{
    const SDLOP_KeyName *found;
    int count = (int)(sizeof(sdlop_keynames) / sizeof(sdlop_keynames[0]));

    /* printable ASCII is its own name, like SDL3 */
    if (key == SDLK_UNKNOWN) {
        return "Unknown";
    }
    if (key > 0x20 && key < 0x7F) {
        static char sdlop_ascii_name[2];
        sdlop_ascii_name[0] = (char)key;
        sdlop_ascii_name[1] = '\0';
        return sdlop_ascii_name;
    }
    for (int i = 0; i < count; i++) {
        if (sdlop_keynames[i].code == (SDL_Keycode)key) {
            found = &sdlop_keynames[i];
            return found->name;
        }
    }
    return "Unknown";
}

SDL_Keycode SDL_GetKeyFromName(const char *name)
{
    const SDLOP_KeyName *found;
    int count = (int)(sizeof(sdlop_keynames) / sizeof(sdlop_keynames[0]));

    if (!name || !name[0]) {
        SDL_InvalidParamError("name");
        return SDLK_UNKNOWN;
    }
    if (name[1] == '\0' && (unsigned char)name[0] > 0x20 && (unsigned char)name[0] < 0x7F) {
        /* a single printable character is <-> its own keycode, except that
           letters are stored lowercase in SDLK_* */
        char c = name[0];
        if (c >= 'A' && c <= 'Z') {
            return (SDL_Keycode)(c - 'A' + 'a');
        }
        return (SDL_Keycode)(unsigned char)c;
    }
    for (int i = 0; i < count; i++) {
        if (SDL_strcasecmp(sdlop_keynames[i].name, name) == 0) {
            found = &sdlop_keynames[i];
            return found->code;
        }
    }
    return SDLK_UNKNOWN;
}

/* ------------------------------------------------------------------------- */
/* Scancode <-> keycode                                                      */
/* ------------------------------------------------------------------------- */

static Uint32 sdlop_modifier_scancode_to_keycode(SDL_Scancode scancode)
{
    switch (scancode) {
        case SDL_SCANCODE_LCTRL: return SDLK_LCTRL;
        case SDL_SCANCODE_LSHIFT: return SDLK_LSHIFT;
        case SDL_SCANCODE_LALT: return SDLK_LALT;
        case SDL_SCANCODE_LGUI: return SDLK_LGUI;
        case SDL_SCANCODE_RCTRL: return SDLK_RCTRL;
        case SDL_SCANCODE_RSHIFT: return SDLK_RSHIFT;
        case SDL_SCANCODE_RALT: return SDLK_RALT;
        case SDL_SCANCODE_RGUI: return SDLK_RGUI;
        default: break;
    }
    return 0;
}

SDL_Keycode SDL_GetKeyFromScancode(SDL_Scancode scancode, SDL_Keymod modstate, bool key_event)
{
    Uint32 base;

    (void)key_event;
    if (scancode < 0 || scancode >= SDLOP_NUM_SCANCODES) {
        SDL_InvalidParamError("scancode");
        return SDLK_UNKNOWN;
    }
    base = (Uint32)sdlop_modifier_scancode_to_keycode(scancode);
    if (!base) {
        base = (Uint32)sdlop_keycode_for_scancode[scancode];
    }
    if (base == 0) {
        return SDLK_UNKNOWN;
    }

    if (modstate & SDL_KMOD_SHIFT) {
        Uint32 shifted = (Uint32)sdlop_shifted_keycode_for_scancode[scancode];
        if (shifted) {
            return (SDL_Keycode)shifted;
        }
    }
    if (modstate & SDL_KMOD_CAPS) {
        if (base >= 'a' && base <= 'z') {
            return (SDL_Keycode)(base - 'a' + 'A');
        }
    }
    return (SDL_Keycode)base;
}

SDL_Scancode SDL_GetScancodeFromKey(SDL_Keycode key, SDL_Keymod *modstate)
{
    SDL_Scancode scancode = SDL_SCANCODE_UNKNOWN;
    Uint32 search = (Uint32)key;

    if (modstate) {
        *modstate = SDL_KMOD_NONE;
    }

    /* uppercase letters and shifted characters map back to the unshifted key */
    if (search >= 'A' && search <= 'Z') {
        if (modstate) {
            *modstate |= SDL_KMOD_SHIFT;
        }
        search = search - 'A' + 'a';
    } else if (search > 0x20 && search < 0x7F) {
        for (int i = 0; i < SDLOP_NUM_SCANCODES; i++) {
            if ((Uint32)sdlop_shifted_keycode_for_scancode[i] == search) {
                if (modstate) {
                    *modstate |= SDL_KMOD_SHIFT;
                }
                search = (Uint32)sdlop_keycode_for_scancode[i];
                break;
            }
        }
    }

    for (int i = 0; i < SDLOP_NUM_SCANCODES; i++) {
        if ((Uint32)sdlop_keycode_for_scancode[i] == search) {
            scancode = (SDL_Scancode)i;
            break;
        }
    }
    /* keypad keys carry SDL_SCANCODE_MASK, which the table already reflects */
    return scancode;
}

