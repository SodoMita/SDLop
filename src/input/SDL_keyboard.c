const bool *SDL_GetKeyboardState(int *numkeys)
{
    if (numkeys) {
        *numkeys = SDL_SCANCODE_COUNT;
    }
    return sdlop_keystate;
}

SDL_Keymod SDL_GetModState(void)
{
    return sdlop_modstate;
}

void SDL_SetModState(SDL_Keymod modstate)
{
    sdlop_modstate = modstate;
}

void SDL_ResetKeyboard(void)
{
    memset(sdlop_keystate, 0, sizeof(sdlop_keystate));
}

void SDLOP_ResetKeyboardState(void)
{
    memset(sdlop_keystate, 0, sizeof(sdlop_keystate));
    sdlop_modstate = SDL_KMOD_NONE;
    /* the compositor/window manager keeps its own idea of the modifier state,
       so clear ours again on the next key event rather than faking releases */
}

bool SDLOP_KeyboardStateGet(SDL_Scancode scancode)
{
    if (scancode < 0 || scancode >= SDL_SCANCODE_COUNT) {
        return false;
    }
    return sdlop_keystate[scancode];
}

void SDLOP_SetKeyboardFocus(SDL_Window *window)
{
    if (sdlop_text_input_window && sdlop_text_input_window != window) {
        /* text input follows the keyboard focus */
        sdlop_text_input_window = window;
    }
}

static SDL_Keymod sdlop_modstate_for_scancode(SDL_Scancode scancode, bool down)
{
    SDL_Keymod bit = SDL_KMOD_NONE;
    switch (scancode) {
        case SDL_SCANCODE_LSHIFT: bit = SDL_KMOD_LSHIFT; break;
        case SDL_SCANCODE_RSHIFT: bit = SDL_KMOD_RSHIFT; break;
        case SDL_SCANCODE_LCTRL: bit = SDL_KMOD_LCTRL; break;
        case SDL_SCANCODE_RCTRL: bit = SDL_KMOD_RCTRL; break;
        case SDL_SCANCODE_LALT: bit = SDL_KMOD_LALT; break;
        case SDL_SCANCODE_RALT: bit = SDL_KMOD_RALT; break;
        case SDL_SCANCODE_LGUI: bit = SDL_KMOD_LGUI; break;
        case SDL_SCANCODE_RGUI: bit = SDL_KMOD_RGUI; break;
        case SDL_SCANCODE_NUMLOCKCLEAR: bit = SDL_KMOD_NUM; break;
        case SDL_SCANCODE_CAPSLOCK: bit = SDL_KMOD_CAPS; break;
        case SDL_SCANCODE_MODE: bit = SDL_KMOD_MODE; break;
        case SDL_SCANCODE_SCROLLLOCK: bit = SDL_KMOD_SCROLL; break;
        default: return SDL_KMOD_NONE;
    }
    if (down) {
        sdlop_modstate |= bit;
    } else {
        /* num/caps/scroll are toggles: the caller decides by passing the state
           it wants, so only clear the plain modifiers here */
        if (bit != SDL_KMOD_CAPS && bit != SDL_KMOD_NUM && bit != SDL_KMOD_SCROLL) {
            sdlop_modstate &= (SDL_Keymod)~bit;
        }
    }
    return bit;
}

void SDLOP_SetModStateBit(SDL_Keymod bit, bool down)
{
    if (down) {
        sdlop_modstate |= bit;
    } else {
        sdlop_modstate &= (SDL_Keymod)~bit;
    }
}

void SDLOP_SendKeyEvent(SDL_Scancode scancode, SDL_Keycode keycode, SDL_Keymod modstate,
                        bool down, bool repeat, Uint64 timestamp, Uint32 evdev_code)
{
    SDL_Event event;
    SDL_Window *focus = SDLOP_GetKeyboardFocusWindow();

    if (scancode < 0 || scancode >= SDL_SCANCODE_COUNT) {
        return;
    }

    /* A layout the platform provided wins over the built-in tables: it is the
       only way to get "q"/"a"/"z" right on a non-US keyboard, and it already
       accounts for the current modifier state. */
    if (keycode == SDLK_UNKNOWN && evdev_code && sdlop_key_layout &&
        sdlop_key_layout->keycode_from_evdev) {
        keycode = sdlop_key_layout->keycode_from_evdev(evdev_code);
    }

    if (down) {
        if (sdlop_keystate[scancode] && !repeat) {
            /* the key was already down and this is not a repeat: the app missed
               the release (focus change); treat it as a fresh press */
            sdlop_keystate[scancode] = false;
        }
        sdlop_keystate[scancode] = true;
    } else {
        if (repeat) {
            return;
        }
        sdlop_keystate[scancode] = false;
    }

    sdlop_modstate_for_scancode(scancode, down);
    if (modstate != SDL_KMOD_NONE && !(scancode == SDL_SCANCODE_CAPSLOCK)) {
        sdlop_modstate = modstate;
    }

    /* SDL3 only reports key repeats for apps that asked for text input */
    if (repeat && !sdlop_text_input_enabled) {
        return;
    }

    memset(&event, 0, sizeof(event));
    event.type = down ? SDL_EVENT_KEY_DOWN : SDL_EVENT_KEY_UP;
    event.key.timestamp = timestamp;
    event.key.windowID = focus ? focus->id : 0;
    event.key.which = 1;
    event.key.scancode = scancode;
    event.key.key = keycode ? keycode : SDL_GetKeyFromScancode(scancode, sdlop_modstate, true);
    event.key.mod = sdlop_modstate;
    event.key.down = down;
    event.key.repeat = repeat;
    SDLOP_PushEvent(&event);

    SDLOP_HandleTextInputForKey(scancode, event.key.key, evdev_code, down, timestamp);
}

void SDLOP_SendKeymapChanged(Uint64 timestamp)
{
    SDL_Event event;
    memset(&event, 0, sizeof(event));
    event.type = SDL_EVENT_KEYMAP_CHANGED;
    event.common.timestamp = timestamp;
    SDLOP_PushEvent(&event);
}

